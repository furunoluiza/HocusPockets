class CatalyticCav:
    def __init__(self, cavities_path, rslrd_file, fukui_file, verbose_handler):
        """
        Initializes the CatalyticCav object for processing cavity descriptors using reactivity data.

        Input:
            cavities_path   [str] - Path to the directory containing cavity files.
            rslrd_file      [str] - Path to the .rslrd file generated by PRIMoRDiA containing residue descriptors.
            fukui_file      [str] - Path to the Fukui potential .pdb file generated by PRIMoRDiA.
            verbose_handler [obj] - Instance of VerboseHandler used for logging messages.

        Attributes:
            self.fukushima_dict [dict] - Dictionary containing Fukushima descriptors loaded from the .rslrd file.
            self.fukui_dict     [dict] - Dictionary containing Fukui potential values loaded from the .pdb file.
        """
        self.cavities_path = cavities_path
        self.verbose_handler = verbose_handler
        self.rslrd_file = rslrd_file
        self.fukui_file = fukui_file
        self.fukushima_dict, self.fukui_dict = self.load_data()

    def process_fukui_cav(self):
        """
        Identifica resíduos catalíticos com base nos maiores valores de Fukui
        extraídos da coluna B-factor do arquivo PDB. Os resíduos com pelo menos
        um átomo entre os 10% maiores valores são considerados catalíticos e são
        salvos em um novo arquivo PDB.
        """
        if not os.path.exists(self.fukui_file):
            self.verbose_handler.output(f"[ERROR] Fukui file {self.fukui_file} not found.")
            return

        atoms = []
        values = []

        # Leitura do arquivo PDB
        with open(self.fukui_file, 'r') as file:
            for line in file:
                if line.startswith("ATOM"):
                    try:
                        bfactor = float(line[60:66].strip())
                        values.append(bfactor)
                        atoms.append((line, bfactor))
                    except ValueError:
                        continue

        if not values:
            self.verbose_handler.output("[WARNING] Fukui value not found in B-factor.")
            return

        # Define o ponto de corte para os 20% maiores valores
        values.sort()
        cutoff_index = int(0.9 * len(values))
        cutoff_value = values[cutoff_index]

        self.verbose_handler.output(f"[INFO] Fukui cutoff: {cutoff_value:.4f} (top 10%)")

        # Seleciona linhas com valor acima do cutoff
        selected_lines = []
        selected_residues = set()

        for line, b in atoms:
            if b >= cutoff_value:
                res_id = line[22:26].strip() + line[17:20].strip()  # número + nome
                selected_residues.add(res_id)

        # Salva todos os átomos dos resíduos selecionados
        for line, _ in atoms:
            res_id = line[22:26].strip() + line[17:20].strip()
            if res_id in selected_residues:
                selected_lines.append(line)

        # Cria diretório e salva o arquivo
        fukui_dir = os.path.join(self.cavities_path, 'fukui')
        os.makedirs(fukui_dir, exist_ok=True)
        output_file = os.path.join(fukui_dir, 'fukui_catalytic.pdb')

        with open(output_file, 'w') as out:
            out.writelines(selected_lines)


    def load_data(self):
        fukushima_data = {}
        fukui_data = {}
        with open(self.rslrd_file, 'r') as file:
            for line in file:
                if line.startswith('#') or not line.strip():
                    continue
                parts = line.strip().split()
                res_id = parts[0]  # Ex: "1MET"
                fukushima_value = float(parts[13])  # Fukushima está na 14ª coluna (índice 13)
                fukui_value = float(parts[9])
                fukushima_data[res_id] = fukushima_value
                fukui_data[res_id] = fukui_value
        return fukushima_data, fukui_data
    
    def get_residues_from_pdb(self, pdb_path):
        residues = set()
        with open(pdb_path, 'r') as file:
            for line in file:
                if line.startswith("ATOM"):
                    res_seq = int(line[22:26].strip()) - 1
                    res_name = line[17:20].strip()
                    residue_id = f"{res_seq}{res_name}"
                    residues.add(residue_id)
        return residues

    def compute_average(self): #O arquivo .rslrd possue info de cadeia, talvez melhor extrair do .pdb
        """
        Computes the average Fukui and Fukushima values for each cavity found
        by Fpocket and ConCavity (ligsite, surfnet, pocketfinder).

        Return:
            Tuple of two dictionaries:
                - results_fukushima [(program, pocket_file)] → average Fukushima value
                - results_fukui     [(program, pocket_file)] → average Fukui value
        """
        cavity_programs = ['fpocket', 'ligsite', 'surfnet', 'pocketfinder']
        results_fukushima = {}
        results_fukui = {}
        for program in cavity_programs:
            program_dir = os.path.join(self.cavities_path, program)
            if not os.path.exists(program_dir):
                self.verbose_handler.output(f"[WARNING] Skipping missing cavity directory: {program_dir}")
                continue
            for pocket_file in os.listdir(program_dir):
                # Only consider PDB files of residues
                if pocket_file.startswith("residue") and pocket_file.endswith(".pdb"):
                    pocket_path = os.path.join(program_dir, pocket_file)
                    residues = self.get_residues_from_pdb(pocket_path)
                    # Compute average Fukushima score
                    fukushima_values = [
                        self.fukushima_dict[res] for res in residues if res in self.fukushima_dict
                    ]
                    avg_fukushima = sum(fukushima_values) / len(fukushima_values) if fukushima_values else None
                    # Compute average Fukui
                    fukui_values = [
                        self.fukui_dict[res] for res in residues if res in self.fukui_dict
                    ]
                    avg_fukui = sum(fukui_values) / len(fukui_values) if fukui_values else None

                    results_fukushima[(program, pocket_file)] = avg_fukushima
                    results_fukui[(program, pocket_file)] = avg_fukui
                    self.verbose_handler.output(
                        f"[INFO] {program}/{pocket_file} -> "
                        f"Avg. Fukushima: {avg_fukushima}, Avg. Fukui: {avg_fukui}"
                    )
        return results_fukushima, results_fukui