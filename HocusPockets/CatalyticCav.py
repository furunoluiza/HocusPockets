class CatalyticCav:
    def __init__(self, cavities_path, rslrd_file, pdb_path, fukui_file, verbose_handler):
        """
        Initializes the CatalyticCav object using the .rslrd file and the input .pdb file
        to map descriptors to residues with chain information.

        Input:
            cavities_path [str]: Path to the directory containing cavity files.
            rslrd_file    [str]: Path to the .rslrd file generated by PRIMoRDiA.
            pdb_path      [str]: Path to the original input PDB file.
            
            verbose_handler [VerboseHandler]: Logger for output.
        """
        self.cavities_path = cavities_path
        self.rslrd_file = rslrd_file
        self.pdb_path = pdb_path
        self.fukui_file = fukui_file
        self.verbose_handler = verbose_handler
        self.residue_index_to_id = self._extract_residue_index_mapping()
        self.fukushima_dict, self.fukui_dict = self._load_rslrd_with_chain_ids()

    def _extract_residue_index_mapping(self):
            """
            Creates a mapping between the sequential residue index (as used in the .rslrd file)
            and the residue ID in the format 'chain:resSeqresName' (e.g., 'A:42LYS') from the original PDB file.

            This is necessary because the .rslrd file does not contain chain IDs, but residues
            appear in the same order as in the input PDB. This method walks through the PDB and
            captures each unique residue (based on resSeq and chain ID) in order.
            Input:
                Nothing.
            Return:
                residue_map [dict]: Maps index (1-based) → 'chain:resSeqresName'
            """
            residue_map = {} # Final mapping from sequential index to full residue ID
            seen = set() # To track residues already encountered (avoid duplicates)
            index = 1 # Start indexing at 1 to match the .rslrd file
            with open(self.pdb_path, 'r') as pdb:
                for line in pdb:
                    if line.startswith("ATOM"):
                        chain_id = line[21].strip()
                        res_seq = line[22:26].strip()
                        res_name = line[17:20].strip()
                        res_id = f"{chain_id}:{res_seq}{res_name}" # Construct full residue ID

                        if res_id not in seen:
                            seen.add(res_id)
                            residue_map[index] = res_id # Map current index to the residue ID
                            index += 1
            self.verbose_handler.output(f"[INFO] Extracted {len(residue_map)} residues with chain IDs from PDB.")
            return residue_map

    def _load_rslrd_with_chain_ids(self):
        """
        Loads Fukushima and Fukui descriptor values from the .rslrd file and maps them
        to the corresponding residue IDs (with chain information) using the sequential index.

        The .rslrd file provides descriptor values per residue, but only includes an index like '1VAL'.
        We strip off the residue name and use the numerical part to map into the full residue ID
        extracted from the original PDB via _extract_residue_index_mapping().
        Input:
            Nothing.
        Return:
            Tuple of two dictionaries:
                - fukushima_dict [dict]: residue_id → Fukushima value (column 14)
                - fukui_dict     [dict]: residue_id → Fukui_pot_zero value (column 10)
        """
        fukushima_dict = {} # Final dictionary mapping residue ID → Fukushima score
        fukui_dict = {} # Final dictionary mapping residue ID → Fukui score
        with open(self.rslrd_file, 'r') as rslrd:
            for line in rslrd:
                if line.startswith("#") or not line.strip():
                    continue
                parts = line.strip().split()
                if len(parts[0]) < 4 or not parts[0][-3:].isalpha():
                    continue  # skip malformed or header lines
                try:
                    index = int(parts[0][:-3]) # Extract the numeric index (e.g., from '1VAL' → 1)
                except ValueError:
                    self.verbose_handler.output(f"[WARNING] Skipping malformed line in RSLRD: {line.strip()}")
                    continue
                res_id = self.residue_index_to_id.get(index) # Get the full residue ID from mapping
                if res_id:
                    fukui_value = float(parts[9])
                    fukushima_value = float(parts[13])
                    fukui_dict[res_id] = fukui_value
                    fukushima_dict[res_id] = fukushima_value
        self.verbose_handler.output(f"[INFO] Loaded {len(fukushima_dict)} Fukushima and Fukui values from .rslrd.")
        return fukushima_dict, fukui_dict

    def get_residues_from_pdb(self, pdb_path):
        """
        Extracts a set of unique residues from a PDB file, using a composite ID that includes:
        chain ID, residue sequence number, and residue name.
        Input:
            pdb_path [str]: Path to the input PDB file.
        Return:
            [set]: A set of residue IDs in the format 'chain:resSeqresName' (e.g., 'A:42LYS').
        """
        residues = set()
        with open(pdb_path, 'r') as file:
            for line in file:
                if line.startswith("ATOM"):
                    chain_id = line[21].strip()
                    res_seq = line[22:26].strip()
                    res_name = line[17:20].strip()
                    res_id = f"{chain_id}:{res_seq}{res_name}" # Construct residue ID with chain:resSeqresName format
                    residues.add(res_id)
        return residues

    def compute_average(self):
        """
        Computes the average Fukushima and Fukui descriptor values for each predicted cavity,
        grouped by the cavity detection method.
        Each pocket file (residue*.pdb) is parsed to identify its constituent residues,
        and the descriptors are averaged across them using precomputed maps.
        Input:
            Nothing.
        Return:
            Tuple:
                - results_fukushima [dict]: Maps (method, pocket_file) to average Fukushima value.
                - results_fukui     [dict]: Maps (method, pocket_file) to average Fukui value.
        """
        cavity_programs = ['fpocket', 'ligsite', 'surfnet', 'pocketfinder']
        results_fukushima = {}
        results_fukui = {}
        # Loop over each cavity detection method
        for program in cavity_programs:
            program_dir = os.path.join(self.cavities_path, program)
            if not os.path.exists(program_dir):
                self.verbose_handler.output(f"[WARNING] Skipping missing cavity directory: {program_dir}")
                continue
            # Process each pocket file within the method directory
            for pocket_file in os.listdir(program_dir):
                if pocket_file.startswith("residue") and pocket_file.endswith(".pdb"):
                    pocket_path = os.path.join(program_dir, pocket_file)
                    residues = self.get_residues_from_pdb(pocket_path)
                    # Retrieve Fukushima values for the residues
                    fukushima_values = [self.fukushima_dict[r] for r in residues if r in self.fukushima_dict]
                    avg_fukushima = sum(fukushima_values) / len(fukushima_values) if fukushima_values else None
                    # Retrieve Fukui values for the residues
                    fukui_values = [self.fukui_dict[r] for r in residues if r in self.fukui_dict]
                    avg_fukui = sum(fukui_values) / len(fukui_values) if fukui_values else None
                    # Store the averages by method and file
                    results_fukushima[(program, pocket_file)] = avg_fukushima
                    results_fukui[(program, pocket_file)] = avg_fukui
                    self.verbose_handler.output(
                        f"[INFO] {program}/{pocket_file} -> Avg. Fukushima: {avg_fukushima}, Avg. Fukui: {avg_fukui}"
                    )
        return results_fukushima, results_fukui

    def process_fukui_cav(self):
        """
        Identifies catalytic residues based on the top 10% Fukui values (from B-factor column)
        in the Fukui PDB file (which lacks chain information), but maps back to residues with
        chain using the original input PDB.
        The output is a new PDB file containing all atoms of the residues considered catalytic.
        Input:
            Nothing.
        Return:
            Nothing.
        """
        if not os.path.exists(self.pdb_path):
            self.verbose_handler.output(f"[ERROR] Original PDB file not found: {self.pdb_path}")
            return
        fukui_bfactors = []
        # Step 1: Extract B-factors from the Fukui PDB (assumed to be in same atom order as original PDB)
        with open(self.fukui_file, 'r') as f:
            for line in f:
                if line.startswith("ATOM"):
                    try:
                        bfactor = float(line[60:66].strip())
                        fukui_bfactors.append(bfactor)
                    except ValueError:
                        fukui_bfactors.append(0.0)
        if not fukui_bfactors:
            self.verbose_handler.output("[WARNING] No B-factor values found in Fukui file.")
            return
        # Step 2: Compute cutoff
        sorted_bf = sorted(fukui_bfactors)
        cutoff_index = int(0.9 * len(sorted_bf))
        cutoff_value = sorted_bf[cutoff_index]
        self.verbose_handler.output(f"[INFO] Fukui cutoff: {cutoff_value:.4f} (top 10%)")
        # Step 3: Read original PDB and collect catalytic residues based on cutoff
        selected_residues = set()
        pdb_atoms = []
        with open(self.pdb_path, 'r') as file:
            for i, line in enumerate(file):
                if line.startswith("ATOM") and i < len(fukui_bfactors):
                    chain_id = line[21].strip()
                    res_seq = line[22:26].strip()
                    res_name = line[17:20].strip()
                    res_id = f"{chain_id}:{res_seq}{res_name}"
                    pdb_atoms.append((line, res_id, fukui_bfactors[i]))
                    if fukui_bfactors[i] >= cutoff_value:
                        selected_residues.add(res_id)
        # Step 4: Extract all atoms of selected residues
        selected_lines = [line for line, res_id, _ in pdb_atoms if res_id in selected_residues]
        # Step 5: Save to output file
        fukui_dir = os.path.join(self.cavities_path, 'fukui')
        os.makedirs(fukui_dir, exist_ok=True)
        output_file = os.path.join(fukui_dir, 'residue_0_fukui.pdb')
        with open(output_file, 'w') as out:
            out.writelines(selected_lines)
        self.verbose_handler.output(f"[SUCCESS] Catalytic residues saved to: {output_file}")